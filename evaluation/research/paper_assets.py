"""Generate manuscript tables and figures from frozen evidence.

Tables are LaTeX fragments built from the canonical bundles and the paper data
(numbers either come straight from a verified bundle or through ``\\V{}``
macros); figures are drawn with matplotlib from the same bundles. Each output
records its source experiment, bundle and manifest hash; figures also record
aggregation, units, sample size, caption and a hash of the plotted data.
Nothing is typed by hand.
"""

