def build_supplementary(freeze_dir: Path, out_dir: Path) -> dict[str, str]:
    """Write generated supplementary files; returns file name -> SHA-256.

    Configurations come from verified canonical bundles; result tables are
    regenerated by the freeze exporter (which rejects edited manifests), never
    copied by hand.
    """
    import tempfile

    from evaluation.research.tables import export_evidence_summaries, export_tables

    freeze_dir = Path(freeze_dir)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    ev = Evidence(freeze_dir)
    freeze_id = ev.record["freeze_id"]
    expected = {
        name: e["manifest_sha256"]
        for name, e in ev.entries.items()
        if e["role"] == "canonical"
    }
    bundles = [freeze_dir / "bundles" / name for name in sorted(expected)]
    experiments = []
    for path in bundles:
        problems = verify_bundle(path, expected_manifest_sha256=expected[path.name])
        if problems:
            raise ValueError(f"{path.name} fails verification: {problems}")
        entry = ev.entries[path.name]
        experiments.append(
            {
                "bundle": path.name,
                "note": entry.get("note"),
                "code": entry["code"],
                "seed": entry.get("seed"),
                "dataset": entry["dataset"],
                "environment": entry["environment"],
                "manifest_sha256": entry["manifest_sha256"],
                "config": json.loads((path / "config.json").read_text(encoding="utf-8")),
            }
        )
    files: dict[str, str] = {
        "experiments.json": json.dumps(
            {"freeze_id": freeze_id, "experiments": experiments},
            indent=2,
            sort_keys=True,
        )
        + "\n"
    }
    config_lines = [
        f"# S1. Experiment configurations ({freeze_id})",
        "",
        "Generated by scripts/build_paper_assets.py from the canonical bundles; do not edit.",
        "",
    ]
    for item in experiments:
        code, dataset = item["code"], item["dataset"]
        config_lines += [
            f"## {item['bundle']}",
            "",
            f"- note: {item['note']}",
            f"- code commit: `{code['commit']}` (source tree dirty: {code['source_tree_dirty']})",
            f"- seed: {item['seed']}",
            f"- dataset: {dataset.get('id')} {dataset.get('version')} ({dataset.get('data_origin')})",
            f"- manifest SHA-256: `{item['manifest_sha256']}`",
            "",
            "```json",
            json.dumps(item["config"], indent=2, sort_keys=True),
            "```",
            "",
        ]
    files["S1-configurations.md"] = "\n".join(config_lines)
    with tempfile.TemporaryDirectory() as tmp:
        exports = Path(tmp)
        export_tables(bundles, exports, expected_manifests=expected)
        export_evidence_summaries(
            bundles,
            exports,
            expected_manifests=expected,
            supporting_dir=freeze_dir / "supporting",
        )
        for name, (title, parts) in SUPPLEMENTARY_SECTIONS.items():
            lines = [
                f"# {title}",
                "",
                f"Generated by scripts/build_paper_assets.py from {freeze_id}; do not edit.",
                "",
            ]
            for part in parts:
                lines += [
                    f"## {part.removesuffix('.md')}",
                    "",
                    (exports / part).read_text(encoding="utf-8").strip(),
                    "",
                ]
            files[name] = "\n".join(lines)
    hashes = {}
    for name, text in files.items():
        (out_dir / name).write_text(text, encoding="utf-8", newline="\n")
        hashes[name] = hashlib.sha256(text.encode("utf-8")).hexdigest()
    return hashes


def build_all(freeze_dir: Path, paper_dir: Path) -> dict[str, Any]:
    ev = Evidence(freeze_dir)
    paper_dir = Path(paper_dir)
    (paper_dir / "tables").mkdir(parents=True, exist_ok=True)
    table_hashes = {}
    for name, text in build_tables(ev).items():
        path = paper_dir / "tables" / f"{name}.tex"
        path.write_text(text, encoding="utf-8", newline="\n")
        table_hashes[path.name] = hashlib.sha256(text.encode("utf-8")).hexdigest()
    figures = build_figures(ev, paper_dir / "figures")
    supplementary = build_supplementary(
        freeze_dir, paper_dir / "supplementary" / "generated"
    )
    provenance = {
        "freeze_id": ev.record["freeze_id"],
        "tables": table_hashes,
        "figures": figures,
        "supplementary": supplementary,
    }
    (paper_dir / "figures" / "figures.json").write_text(
        json.dumps(provenance, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return provenance
