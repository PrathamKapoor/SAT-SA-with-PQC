class Evidence:
    """Verified access to canonical bundles of one freeze."""

    def __init__(self, freeze_dir: Path) -> None:
        self.freeze_dir = Path(freeze_dir)
        record = json.loads(
            (self.freeze_dir / "freeze.json").read_text(encoding="utf-8")
        )
        self.record = record
        self.entries = {b["bundle"]: b for b in record["bundles"]}
        self._cache: dict[str, dict[str, Any]] = {}

    def results(self, experiment: str) -> dict[str, Any]:
        name = EXP_BUNDLE[experiment]
        if name not in self._cache:
            entry = self.entries[name]
            if entry["role"] != "canonical":
                raise ValueError(f"{name} is not canonical")
            path = self.freeze_dir / "bundles" / name
            problems = verify_bundle(
                path, expected_manifest_sha256=entry["manifest_sha256"]
            )
            if problems:
                raise ValueError(f"{name} fails verification: {problems}")
            self._cache[name] = json.loads(
                (path / "raw" / "results.json").read_text(encoding="utf-8")
            )
        return self._cache[name]

    def source(self, *experiments: str) -> str:
        return "; ".join(
            f"{e}={EXP_BUNDLE[e]} (manifest {self.entries[EXP_BUNDLE[e]]['manifest_sha256'][:16]})"
            for e in experiments
        )


def _esc(text: Any) -> str:
    out = str(text)
    for a, b in (
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("_", r"\_"),
        ("#", r"\#"),
    ):
        out = out.replace(a, b)
    return out


def _minus(cell: str) -> str:
    """Typeset negative numbers with a minus sign rather than a hyphen."""
    return re.sub(r"(?<![\w\\-])-(?=\d)", r"\\ensuremath{-}", cell)


def _table(
    ev: Evidence,
    experiments: tuple[str, ...],
    label: str,
    caption: str,
    columns: str,
    header: list[str],
    rows: list[list[str]],
    note: str = "",
) -> str:
    lines = [
        f"% Generated by scripts/build_paper_assets.py from {ev.record['freeze_id']}; do not edit.",
        f"% Sources: {ev.source(*experiments) if experiments else 'code facts and deployment record'}",
        "\\begin{table}[t]",
        "\\centering\\small",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\begin{adjustbox}{max width=\\linewidth}",
        f"\\begin{{tabular}}{{{columns}}}",
        "\\toprule",
        " & ".join(header) + " \\\\",
        "\\midrule",
        *[" & ".join(_minus(c) for c in r) + " \\\\" for r in rows],
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{adjustbox}",
    ]
    if note:
        lines.append(f"\\par\\smallskip\\footnotesize {note}")
    lines.append("\\end{table}")
    return "\n".join(lines) + "\n"


