def build_figures(ev: Evidence, out_dir: Path) -> list[dict[str, Any]]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update(
        {"font.size": 8, "figure.dpi": 150, "savefig.bbox": "tight", "pdf.fonttype": 42}
    )
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    index: list[dict[str, Any]] = []

    def save(
        fig, fid: str, experiments: tuple[str, ...], data: Any, meta: dict[str, Any]
    ) -> None:
        path = out_dir / f"{fid}.pdf"
        fig.savefig(path, metadata={"CreationDate": None, "ModDate": None})
        plt.close(fig)
        index.append(
            {
                "figure_id": fid,
                "file": f"figures/{path.name}",
                "experiments": list(experiments),
                "source": ev.source(*experiments),
                "data_sha256": hashlib.sha256(
                    json.dumps(data, sort_keys=True, default=str).encode()
                ).hexdigest(),
                **meta,
            }
        )

    # Prioritization
    reps = ev.results("PR01")["metrics"]["replicates"]
    methods = [
        ("satsa", "SAT-SA"),
        ("fastest_median_closure", "Fastest\nclosure"),
        ("critical_alert_volume", "Alert\nvolume"),
        ("random", "Random\n(mean)"),
    ]
    data = {m: [r["methods"][m]["20"]["recall"] for r in reps] for m, _ in methods}
    fig, ax = plt.subplots(figsize=(3.4, 2.2))
    ax.boxplot(
        [data[m] for m, _ in methods], tick_labels=[l for _, l in methods], widths=0.5
    )
    for i, (m, _) in enumerate(methods, 1):
        ax.scatter([i] * len(data[m]), data[m], s=6, alpha=0.5)
    ax.set_ylabel("recall@20%")
    save(
        fig,
        "fig-prioritization",
        ("PR01",),
        data,
        {
            "x": "method",
            "y": "recall at top 20% (4 of 20 entities)",
            "units": "fraction",
            "aggregation": "one point per generated population; box = median/quartiles",
            "sample_size": len(reps),
            "caption": "Recall@20\\% of generator-labelled pathological entities across 20 generated populations (PR01).",
        },
    )

    # Ablation
    a = ev.results("A01")["metrics"]["scenario_level"]
    full = a["full"]["micro"]
    rows = [("full set", full["precision"], full["recall"])] + [
        (w["worker_removed"], w["micro"]["precision"], w["micro"]["recall"])
        for w in a["workers"]
        if (w["micro"]["precision"], w["micro"]["recall"])
        != (full["precision"], full["recall"])
    ]
    fig, ax = plt.subplots(figsize=(3.4, 2.2))
    y = range(len(rows))
    ax.barh([i + 0.2 for i in y], [r[2] for r in rows], height=0.4, label="recall")
    ax.barh([i - 0.2 for i in y], [r[1] for r in rows], height=0.4, label="precision")
    ax.set_yticks(list(y), [r[0] for r in rows])
    ax.invert_yaxis()
    ax.set_xlim(0, 1.05)
    ax.legend(loc="upper left", bbox_to_anchor=(1.01, 1.0), fontsize=6)
    save(
        fig,
        "fig-ablation",
        ("A01",),
        rows,
        {
            "x": "micro precision / recall",
            "y": "worker removed (only rows that changed)",
            "units": "fraction",
            "aggregation": "micro over 5 catalog scenarios",
            "sample_size": 5,
            "caption": "Catalog micro precision and recall with one worker removed; unchanged removals omitted (A01).",
        },
    )

    # Robustness
    om = ev.results("R01b")["metrics"]["record_omission_by_rate"]
    rates = {
        k: {
            "rejected": v["rejected_by_validation"] / v["replicates"],
            "changed": v["family_set_changed"] / v["replicates"],
        }
        for k, v in om.items()
    }
    fig, axes = plt.subplots(1, 2, figsize=(3.4, 1.8), sharey=True)
    for ax, key, title in (
        (axes[0], "rejected", "rejected"),
        (axes[1], "changed", "finding families changed"),
    ):
        for kind, label in (
            ("omit_records", "independent"),
            ("omit_records_cascade", "cascade"),
        ):
            xs = [0.10, 0.25, 0.50]
            ax.plot(
                xs, [rates[f"{kind}:{x:.2f}"][key] for x in xs], marker="o", label=label
            )
        ax.set_title(title, fontsize=7)
        ax.set_xlabel("omission rate")
    axes[0].set_ylabel("fraction of 25 replicates")
    axes[1].legend(fontsize=6)
