"""Provenance tagging — the one rule this whole package exists to
enforce: every record derived from a public dataset or generated by
the workflow augmentation policy carries an explicit, machine-checkable
tag saying exactly where it came from. Nothing produced by this
package is ever silently indistinguishable from a real SOC record.

Two, and only two, provenance types:

* ``derived_from_source`` — computed directly from a real public
  dataset's real telemetry (e.g. a CIC-IDS2017 flow row, a BOTS
  notable event). The underlying signal is real network/security
  telemetry; SAT-SA's own ingestion normalization is the only thing
  applied to it.
* ``derived_synthetic_workflow`` — a case, investigation step,
  escalation, or disposition invented by
  ``public_benchmarks.workflow_augmentation`` according to an explicit
  policy. This is a controlled validation fixture, never a claim about
  real analyst behavior.

A record with neither tag, or a self-reported tag that doesn't match
where the record actually came from, is a bug in this package — see
``tests/test_phase81_public_benchmarks_provenance.py`` for the tests
that would catch either.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Optional

DERIVED_FROM_SOURCE = "derived_from_source"
DERIVED_SYNTHETIC_WORKFLOW = "derived_synthetic_workflow"
PROVENANCE_TYPES = (DERIVED_FROM_SOURCE, DERIVED_SYNTHETIC_WORKFLOW)

GENERATION_POLICY_VERSION = "workflow-policy-v1"


@dataclass(frozen=True)
class ProvenanceTag:
    """Attached to every record this package produces. ``to_dict()``
    is the exact shape the user's own instruction specified — a
    machine-readable, storable/queryable tag, not a comment."""

    provenance_type: str
    source_dataset: str
    scenario_id: str = ""
    generation_policy_version: str = ""

    def __post_init__(self) -> None:
        if self.provenance_type not in PROVENANCE_TYPES:
            raise ValueError(
                f"provenance_type must be one of {PROVENANCE_TYPES}, "
                f"got {self.provenance_type!r}")
        if not self.source_dataset.strip():
            raise ValueError("source_dataset must be non-empty — every "
                              "record must name where it came from")
        if (self.provenance_type == DERIVED_SYNTHETIC_WORKFLOW
                and not self.generation_policy_version.strip()):
            raise ValueError(
                "a derived_synthetic_workflow record must carry the "
                "generation_policy_version it was produced under")

    def to_dict(self) -> dict:
        return asdict(self)


def source_derived(source_dataset: str) -> ProvenanceTag:
    """Tag for a record computed directly from real public telemetry
    (an alert or asset derived from CIC-IDS2017 / BOTS)."""
    return ProvenanceTag(
        provenance_type=DERIVED_FROM_SOURCE, source_dataset=source_dataset)


def synthetic_workflow(source_dataset: str, *, scenario_id: str,
                       policy_version: str = GENERATION_POLICY_VERSION,
                       ) -> ProvenanceTag:
    """Tag for a case/investigation_step/escalation/disposition
    invented by the workflow augmentation generator."""
    return ProvenanceTag(
        provenance_type=DERIVED_SYNTHETIC_WORKFLOW,
        source_dataset=source_dataset, scenario_id=scenario_id,
        generation_policy_version=policy_version)


def is_real_soc_data(tag: ProvenanceTag) -> bool:
    """Always False for every tag this package can produce — exists
    as a single, greppable assertion point: nothing in this package
    is ever real SOC data, by construction. A caller that needs to
    distinguish "real" data (e.g. from an actual CSE submission) from
    benchmark data should check for the *absence* of a ProvenanceTag,
    not call this function expecting True from anything here."""
    return False
