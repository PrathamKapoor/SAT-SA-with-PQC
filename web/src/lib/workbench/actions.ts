/** multipart: version_id, category, key, file */
export async function uploadArtifactAction(form: FormData): Promise<ActionResult<Artifact>> {
  const versionId = text(form.get("version_id"));
  const category = text(form.get("category")) as EvidenceCategory;
  const key = text(form.get("key"));
  const file = form.get("file");
  if (!(file instanceof File) || !EVIDENCE_CATEGORIES.includes(category) || !versionId || !key) {
    return { ok: false, error: { status: 422, code: "VALIDATION_ERROR", message: "A file, a category and a submission version are required.", requestId: "", details: [] } };
  }
  return act(() => api.uploadArtifact(versionId, category, file, key));
}

