/**
 * Every write the workbench performs, one backend route each
 * (docs/API_CONTRACT.md). Idempotency keys are generated by the caller per
 * logical step and reused on retry, so a repeated click returns the original
 * resource instead of creating a second one.
 */

const text = (v: FormDataEntryValue | null) => (typeof v === "string" ? v.trim() : "");

export async function createEntityAction(input: { display_name: string; sector: string; environment_class: string }): Promise<ActionResult<Entity>> {
  const r = await act(() => api.createEntity(input));
  if (r.ok) revalidatePath("/workbench", "layout");
  return r;
}

